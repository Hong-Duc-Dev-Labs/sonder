//! Generates the DSD→PCM decimation tables at build time.
//!
//! Each table is a Kaiser-windowed sinc low-pass FIR, normalised to unity DC gain. The
//! specification is fixed here, not tuned per file: passband to 20 kHz, stopband at the
//! decimator output's Nyquist frequency, ≥120 dB attenuation, β = 12.
//!
//! Table lengths are chosen so the widest transition in each stage gets the attenuation:
//! 255 taps for the /8 stage and the /8 second stage of DSD256→176.4k, 127 for /4 and 63
//! for /2.

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

const PASS_HZ: f64 = 20_000.0;
const BETA: f64 = 12.0;

struct Table {
    name: &'static str,
    taps: usize,
    input_hz: f64,
    stop_hz: f64,
}

const TABLES: [Table; 8] = [
    // First stage: decimate the DSD bit stream by 8. The stopband is the Nyquist frequency
    // of the /8 output, so nothing folds back into the next stage.
    Table {
        name: "TAPS_A_DSD64",
        taps: 255,
        input_hz: 2_822_400.0,
        stop_hz: 2_822_400.0 / 16.0,
    },
    Table {
        name: "TAPS_A_DSD128",
        taps: 255,
        input_hz: 5_644_800.0,
        stop_hz: 5_644_800.0 / 16.0,
    },
    Table {
        name: "TAPS_A_DSD256",
        taps: 255,
        input_hz: 11_289_600.0,
        stop_hz: 11_289_600.0 / 16.0,
    },
    // Second stage, chosen by the remaining ratio and the PCM output rate.
    Table {
        name: "TAPS_B_176_2",
        taps: 63,
        input_hz: 352_800.0,
        stop_hz: 88_200.0,
    },
    Table {
        name: "TAPS_B_176_4",
        taps: 127,
        input_hz: 705_600.0,
        stop_hz: 88_200.0,
    },
    Table {
        name: "TAPS_B_176_8",
        taps: 255,
        input_hz: 1_411_200.0,
        stop_hz: 88_200.0,
    },
    Table {
        name: "TAPS_B_352_2",
        taps: 63,
        input_hz: 705_600.0,
        stop_hz: 176_400.0,
    },
    Table {
        name: "TAPS_B_352_4",
        taps: 127,
        input_hz: 1_411_200.0,
        stop_hz: 176_400.0,
    },
];

fn main() {
    let mut out = String::from("// Generated by build.rs; do not edit.\n");
    for table in TABLES {
        let taps = design(table.taps, table.input_hz, table.stop_hz);
        let _ = write!(
            out,
            "pub(crate) const {}: [f64; {}] = [",
            table.name, table.taps
        );
        out.push('\n');
        for (i, h) in taps.iter().enumerate() {
            if i % 4 == 0 {
                out.push_str("    ");
            }
            let _ = write!(out, "{h:?},");
            if i % 4 == 3 {
                out.push('\n');
            }
        }
        out.push_str("];\n");
    }
    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("dsd_tables.rs");
    fs::write(path, out).unwrap();
    println!("cargo:rerun-if-changed=build.rs");
}

/// Kaiser-windowed sinc, cutoff at the midpoint of the passband and stopband.
fn design(taps: usize, input_hz: f64, stop_hz: f64) -> Vec<f64> {
    assert!(taps % 2 == 1, "odd tap count keeps the filter linear phase");
    let cutoff = (PASS_HZ + stop_hz) / 2.0 / input_hz;
    let m = (taps - 1) as f64;
    let mut h: Vec<f64> = (0..taps)
        .map(|i| {
            let n = i as f64 - m / 2.0;
            let sinc = if n == 0.0 {
                2.0 * cutoff
            } else {
                (std::f64::consts::TAU * cutoff * n).sin() / (std::f64::consts::PI * n)
            };
            let ratio = 2.0 * i as f64 / m - 1.0;
            let window = bessel_i0(BETA * (1.0 - ratio * ratio).max(0.0).sqrt()) / bessel_i0(BETA);
            sinc * window
        })
        .collect();
    let sum: f64 = h.iter().sum();
    for value in &mut h {
        *value /= sum;
    }
    h
}

/// Zeroth-order modified Bessel function, by its power series.
fn bessel_i0(x: f64) -> f64 {
    let mut sum = 1.0;
    let mut term = 1.0;
    let half = x / 2.0;
    for k in 1..50 {
        term *= (half / k as f64) * (half / k as f64);
        sum += term;
        if term < 1e-18 {
            break;
        }
    }
    sum
}
